<?php

namespace App\Http\Controllers;

use Anthropic\Client;
use Anthropic\Core\Exceptions\APIConnectionException;
use Anthropic\Core\Exceptions\APIStatusException;
use Anthropic\Core\Exceptions\AuthenticationException;
use Anthropic\Core\Exceptions\RateLimitException;
use App\Services\KnowledgeBase;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

class KnowledgeBaseController extends Controller
{
    public function __construct(private KnowledgeBase $kb) {}

    /** Staff-only (self-service) users may read HR policies and general references only — never operational analyses
     *  that name other staff or sites. */
    private function allowedPages(Request $r): ?array
    {
        $u = $r->user();
        $staffOnly = $u && $u->hasRole('staff') && !$u->hasAnyRole(['super_admin', 'manager', 'executive', 'site_officer', 'po', 'authenticated']);
        return $staffOnly ? ['hr', 'general'] : null;
    }

    /* ── CRUD ─────────────────────────────────────────────────────────── */

    public function index(Request $req)
    {
        if (!DB::table('knowledge_base')->exists()) $this->kb->refreshAll();
        $q = DB::table('knowledge_base')->select('id', 'title', 'page', 'source', 'slug', 'tags', 'updated_at', 'created_at',
            DB::raw('left(content, 280) AS excerpt'), DB::raw('length(content) AS chars'));
        if ($p = $req->input('page')) $q->where('page', $p);
        if ($allowed = $this->allowedPages($req)) $q->whereIn('page', $allowed);
        if ($s = trim((string) $req->input('q'))) $q->where(fn ($w) => $w->where('title', 'ilike', "%$s%")->orWhere('content', 'ilike', "%$s%"));
        return [
            'entries' => $q->orderByRaw("CASE source WHEN 'manual' THEN 0 WHEN 'auto' THEN 1 ELSE 2 END")->orderByDesc('updated_at')->get(),
            'counts' => DB::table('knowledge_base')->selectRaw('page, count(*) c')->groupBy('page')->pluck('c', 'page'),
            'ai_enabled' => $this->aiEnabled(),
            'last_refresh' => DB::table('knowledge_base')->where('source', 'auto')->max('updated_at'),
        ];
    }

    public function show(Request $req, $id)
    {
        $row = DB::table('knowledge_base')->where('id', $id)->firstOrFail();
        if ($allowed = $this->allowedPages($req)) abort_unless(in_array($row->page, $allowed, true), 403);
        return $row;
    }

    private function denyStaff(Request $r): void { abort_if($this->allowedPages($r), 403, 'Only HR / management can change the knowledge base.'); }

    public function store(Request $req)
    {
        $this->denyStaff($req);
        $data = $req->validate(['title' => 'required|string|max:200', 'content' => 'required|string|max:50000',
            'page' => 'nullable|in:' . implode(',', KnowledgeBase::PAGES), 'tags' => 'nullable|array']);
        $id = DB::table('knowledge_base')->insertGetId(['title' => $data['title'], 'content' => $data['content'], 'page' => $data['page'] ?? 'general',
            'source' => 'manual', 'tags' => json_encode($data['tags'] ?? []), 'created_by' => $req->user()?->id, 'created_at' => now(), 'updated_at' => now()]);
        return DB::table('knowledge_base')->where('id', $id)->first();
    }

    public function update(Request $req, $id)
    {
        $this->denyStaff($req);
        $row = DB::table('knowledge_base')->where('id', $id)->firstOrFail();
        abort_if($row->source !== 'manual', 422, 'Auto snapshots and reference entries are regenerated by the system — add a note instead.');
        $data = $req->validate(['title' => 'sometimes|string|max:200', 'content' => 'sometimes|string|max:50000', 'page' => 'sometimes|in:' . implode(',', KnowledgeBase::PAGES)]);
        DB::table('knowledge_base')->where('id', $id)->update($data + ['updated_at' => now()]);
        return DB::table('knowledge_base')->where('id', $id)->first();
    }

    public function destroy(Request $req, $id)
    {
        $this->denyStaff($req);
        $row = DB::table('knowledge_base')->where('id', $id)->firstOrFail();
        abort_if($row->source === 'reference', 422, 'Reference entries cannot be deleted.');
        DB::table('knowledge_base')->where('id', $id)->delete();
        return ['deleted' => (int) $id];
    }

    /** POST /api/kb/refresh — rebuild snapshots from the live analyses. */
    public function refresh(Request $req)
    {
        $this->denyStaff($req);
        set_time_limit(300);
        $page = $req->input('page');
        return ['refreshed' => $page ? [$page => $this->kb->refresh($page)] : $this->kb->refreshAll(), 'at' => now()->toDateTimeString()];
    }

    /* ── ASK ──────────────────────────────────────────────────────────── */

    private function aiEnabled(): bool { return (bool) config('services.anthropic.key'); }

    private const SYSTEM = <<<'T'
You are the assistant inside the KSSB Smart Monitoring System, a mining-site supervision platform. Managers, executives and site officers ask you about sales, site operations, permits, document compliance, dockets and staff attendance.

Answer only from the knowledge-base entries provided in the user turn. They are generated from the live database and contain the analyses, definitions and recommended actions. If the entries do not contain the answer, say so plainly and suggest which page or data would answer it — do not guess numbers.

How to answer:
- Reply in the language of the question (Bahasa Melayu or English; casual Malay is fine when the user writes that way).
- Lead with the direct answer, then the reason ("kenapa") and, when useful, the recommended action ("tindakan") with its owner.
- Use concrete numbers, site codes and staff names from the entries. Keep it short: a few sentences or a compact bullet list.
- Cite the entries you used as [KB#id] after the sentence they support.
- Use simple Markdown only (bold, bullet lists). No tables, no headings.
T;

    public function ask(Request $req)
    {
        $data = $req->validate(['question' => 'required|string|max:2000', 'page' => 'nullable|string|max:32', 'history' => 'nullable|array|max:12',
            'history.*.role' => 'in:user,assistant', 'history.*.content' => 'string|max:6000']);
        $page = in_array($data['page'] ?? null, KnowledgeBase::PAGES, true) ? $data['page'] : null;
        $this->kb->ensureFresh($page);
        $hits = $this->kb->search($data['question'], $page, 6, $this->allowedPages($req));
        // In the self-service portal the assistant may also read the user's own HR data (never anyone else's).
        if ($page === 'ess' && ($ctx = app(EssController::class)->personalContext($req->user()))) {
            array_unshift($hits, ['id' => 0, 'title' => 'Data peribadi anda (live)', 'page' => 'ess', 'source' => 'personal', 'content' => $ctx,
                'updated_at' => now()->toDateTimeString(), 'rank' => 99]);
        }
        $sources = array_map(fn ($h) => ['id' => $h['id'], 'title' => $h['title'], 'page' => $h['page'], 'source' => $h['source']], $hits);

        $answer = null; $mode = 'search'; $note = null;
        if ($this->aiEnabled()) {
            try {
                $answer = $this->askClaude($data['question'], $page, $hits, $data['history'] ?? []);
                $mode = 'ai';
            } catch (AuthenticationException $e) {
                $note = 'The Anthropic API key was rejected — showing knowledge-base matches instead.';
            } catch (RateLimitException $e) {
                $note = 'The AI service is busy (rate limited) — showing knowledge-base matches instead.';
            } catch (APIStatusException $e) {
                Log::warning('ask: Claude API error', ['type' => $e->type?->value, 'msg' => $e->getMessage()]);
                $note = 'The AI service returned an error — showing knowledge-base matches instead.';
            } catch (APIConnectionException $e) {
                $note = 'Could not reach the AI service — showing knowledge-base matches instead.';
            }
        } else {
            $note = 'AI answers are off (no ANTHROPIC_API_KEY configured) — showing the most relevant knowledge-base entries.';
        }
        if ($answer === null) $answer = $this->extractive($data['question'], $hits);

        DB::table('ask_logs')->insert(['user_id' => $req->user()?->id, 'page' => $page, 'question' => $data['question'], 'answer' => $answer,
            'mode' => $mode, 'kb_ids' => json_encode(array_column($sources, 'id')), 'created_at' => now(), 'updated_at' => now()]);
        return ['answer' => $answer, 'mode' => $mode, 'note' => $note, 'sources' => $sources];
    }

    private function askClaude(string $question, ?string $page, array $hits, array $history): ?string
    {
        $client = new Client(apiKey: config('services.anthropic.key'));
        $ctx = implode("\n\n", array_map(fn ($h) => "<kb id=\"{$h['id']}\" title=\"" . e($h['title']) . "\" page=\"{$h['page']}\" updated=\"{$h['updated_at']}\">\n"
            . mb_substr($h['content'], 0, 24000) . "\n</kb>", $hits));
        $messages = [];
        foreach (array_slice($history, -8) as $m) $messages[] = ['role' => $m['role'], 'content' => $m['content']];
        if ($messages && $messages[0]['role'] !== 'user') array_shift($messages);
        $messages[] = ['role' => 'user', 'content' => "Knowledge-base entries:\n\n$ctx\n\nThe user is on the \"" . ($page ?? 'general') . "\" page. Today is " . now()->toDateString() . ".\n\nQuestion: $question"];

        $msg = $client->messages->create(
            model: config('services.anthropic.model'),
            maxTokens: 8000,
            outputConfig: ['effort' => 'low'],   // short grounded Q&A — low effort keeps answers fast
            system: [['type' => 'text', 'text' => self::SYSTEM, 'cacheControl' => ['type' => 'ephemeral']]],
            messages: $messages,
        );
        if ($msg->stopReason === 'refusal') return null;   // fall back to knowledge-base matches
        $text = '';
        foreach ($msg->content as $block) if ($block->type === 'text') $text .= $block->text;
        return trim($text) !== '' ? trim($text) : null;
    }

    /** No-AI fallback: the most relevant lines from the best entries. */
    private function extractive(string $q, array $hits): string
    {
        if (!$hits) return 'Tiada maklumat berkaitan dalam knowledge base. / Nothing relevant found in the knowledge base.';
        $words = $this->kb->terms($q)->filter(fn ($w) => mb_strlen($w) >= 3)->values();
        $out = [];
        // score every entry by its best-matching lines, then show the 3 most relevant entries
        $ranked = collect($hits)->map(function ($h) use ($words) {
            $lines = array_filter(array_map('trim', explode("\n", $h['content'])), fn ($l) => $l !== '' && !preg_match('/^[A-Z ,()&\/-]+$/', $l));
            $scored = collect($lines)->map(fn ($l) => ['l' => $l, 's' => $words->filter(fn ($w) => str_contains(mb_strtolower($l), $w))->count()])
                ->filter(fn ($x) => $x['s'] > 0)->sortByDesc('s')->take(4);
            return ['h' => $h, 'lines' => $scored->isEmpty() ? collect(array_slice(array_values($lines), 0, 3)) : $scored->pluck('l'),
                'score' => $scored->sum('s') + ($h['rank'] ?? 0) * 0.01];
        })->sortByDesc('score')->take(3);
        foreach ($ranked as $x) $out[] = "**{$x['h']['title']}** [KB#{$x['h']['id']}]\n" . $x['lines']->map(fn ($l) => '- ' . ltrim($l, '- '))->implode("\n");
        return implode("\n\n", $out);
    }
}
